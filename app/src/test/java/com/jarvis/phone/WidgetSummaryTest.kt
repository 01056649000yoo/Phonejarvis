package com.jarvis.phone

import org.junit.Assert.assertEquals
import org.junit.Test

/** 위젯은 요약만: 🙋·💬 칸은 그대로, 나머지 칸(마감·업무·앱 알림 등)은 제목만 한 줄 */
class WidgetSummaryTest {
    @Test fun 요약_칸만_보이고_나머지는_제목_한_줄() {
        val text = """
            📌 오늘·내일 마감 (2건)
            - [오늘] 학예회 명단 제출 (동학년방)
            - [내일] 연수 결과

            🙋 답장할 연락 (1)
            - 서윤 어머니 · 07:42: 2교시 후 등교 가능한지

            💬 사람에게 온 메시지 (2개 방)
            - 동학년방 (5건): 3시 협의회 2층

            📦 앱 알림 (4건 · 요약 안 함)
            - 쿠팡 2건 · 배송 출발
        """.trimIndent()
        assertEquals(listOf(
            "🙋 답장할 연락 (1)", "- 서윤 어머니 · 07:42: 2교시 후 등교 가능한지",
            "💬 사람에게 온 메시지 (2개 방)", "- 동학년방 (5건): 3시 협의회 2층",
            "(📌 오늘·내일 마감 (2건) · 📦 앱 알림 (4건 · 요약 안 함) — 눌러서 보기)",
        ), SummaryWidget.summaryOnly(text))
    }

    @Test fun 내_묶음_요약도_보이고_학부모_정기_알림은_제목만() {
        val text = """
            👪 학부모 연락 (1건, 답장 필요 1)
            - 07:42 지호 어머니: 체험학습 신청서

            👔 교직원 연락 (1명 · 3건)
            - 김민수 선생님 (3건) · 09:00: 내일 3시 협의회, 명단 금요일까지 올리라고 함.

            🔁 정기·자동 알림 2건 (날씨 1, 카카오톡 1) — 요약에서 뺐어요

            (⏱ 6초 · AI 1번 5초)
        """.trimIndent()
        assertEquals(listOf(
            "👔 교직원 연락 (1명 · 3건)", "- 김민수 선생님 (3건) · 09:00: 내일 3시 협의회, 명단 금요일까지 올리라고 함.",
            "(👪 학부모 연락 (1건, 답장 필요 1) · 🔁 정기·자동 알림 2건 (날씨 1, 카카오톡 1) — 눌러서 보기)",
        ), SummaryWidget.summaryOnly(text))
    }
}
